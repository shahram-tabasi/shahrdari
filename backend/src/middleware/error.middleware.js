import env from "../config/env.js";
import * as audit from "../services/audit.service.js";
import { AUDIT_CATEGORY } from "../services/audit.service.js";
import { errorResponse } from "../utils/api-response.js";

/**
 * FAIL-SECURE ERROR HANDLING.
 *
 * The document's requirements are specific, and the previous implementation met
 * none of them: it returned `err.stack` to the client in development and echoed
 * `err.message` verbatim in every environment, so a driver error, a filesystem
 * path or a prompt fragment reached the caller untouched.
 *
 * The rules enforced here:
 *
 *   - Technical error detail is never shown to the user.
 *   - Stack traces are never disclosed, in ANY environment. A developer reads the
 *     stack in the server log, correlated by request id; it never travels in a
 *     response body, because "development" configuration reaching a shared
 *     environment is exactly how these leaks happen.
 *   - System prompts and internal model instructions are never disclosed.
 *   - The user sees a generic, controlled message.
 *
 * Only errors the application raised deliberately (`HttpError`, carrying a
 * 4xx status) are considered safe to describe to the caller. Everything else —
 * an unexpected throw, a 5xx — becomes a generic message plus the request id.
 */

/**
 * Patterns that must never appear in a client-visible message, even inside an
 * intentionally-raised error. This is defence in depth behind the 4xx/5xx rule:
 * a validation message built from an upstream string could still carry one.
 */
const LEAK_PATTERNS = [
  /sk-[A-Za-z0-9_-]{8,}/g,           // API keys
  /Bearer\s+[A-Za-z0-9._~+/-]+=*/gi, // bearer tokens
  /\/(?:home|usr|var|etc|root)\/\S+/g, // filesystem paths
  /\b[A-Za-z]:\\\\\S+/g,             // windows paths
  /(?:postgres|mysql|mongodb|redis):\/\/\S+/gi, // connection strings
  /You are an expert[\s\S]*/i        // system prompt preamble
];

/**
 * @param {string} message
 * @returns {string}
 */
function scrub(message) {
  return LEAK_PATTERNS.reduce(
    (text, pattern) => text.replace(pattern, "[redacted]"),
    message
  );
}

/**
 * Global error handler.
 *
 * @param {Error} err
 * @param {import("express").Request} req
 * @param {import("express").Response} res
 * @param {import("express").NextFunction} next
 */
// eslint-disable-next-line no-unused-vars -- Express identifies the error
// handler by its four-parameter arity; `next` must stay in the signature.
export default function errorMiddleware(err, req, res, next) {
  const statusCode = Number.isInteger(err.statusCode) &&
    err.statusCode >= 400 &&
    err.statusCode <= 599
    ? err.statusCode
    : 500;

  const isClientError = statusCode < 500;

  // The full detail goes to the server log — structured, correlated, and never
  // to the client.
  const logEntry = {
    level: statusCode >= 500 ? "error" : "warn",
    requestId: req.id ?? null,
    method: req.method,
    path: req.path,
    statusCode,
    name: err.name,
    message: err.message,
    stack: env.app.isProduction ? undefined : err.stack
  };

  if (statusCode >= 500) {
    console.error(JSON.stringify(logEntry));
  } else {
    console.warn(JSON.stringify(logEntry));
  }

  audit.record({
    category: AUDIT_CATEGORY.ERROR,
    action: "request.failed",
    outcome: statusCode >= 500 ? "failure" : "denied",
    requestId: req.id,
    actor: req.principal,
    detail: {
      method: req.method,
      path: req.path,
      statusCode,
      name: err.name
    }
  });

  // Only deliberate client errors carry their own message; server faults get a
  // generic one so an internal detail cannot escape through a stray throw.
  const message = isClientError
    ? scrub(err.message || "درخواست نامعتبر است.")
    : "خطای داخلی سامانه رخ داد. در صورت تکرار، شناسه درخواست را به پشتیبانی اعلام کنید.";

  // Validation detail is safe and useful; it is generated by our own schemas.
  // Anything else attached to an error is not returned.
  const errors = isClientError && Array.isArray(err.errors)
    ? err.errors.map(entry => ({
        field: typeof entry.field === "string" ? entry.field : undefined,
        message: scrub(String(entry.message ?? ""))
      }))
    : null;

  res.status(statusCode).json({
    ...errorResponse({ message, errors }),
    meta: { requestId: req.id ?? null }
  });
}
